"""Record human decisions about the data agent accuracy loop.

GENERATED by validation/build_approval_function.py. Edit that and regenerate.

Neither `approved_by` nor `created_by` is a parameter. Both are read from the
caller's Entra token, so a person cannot act as somebody else and a flow
cannot act as a person.

Nothing here applies anything. These functions write rows. A pipeline mirrors
approvals to the eventhouse, and an Activator rule starts the remediation
notebook. If this function could start a notebook, anyone who could call it
could run a job against a governed model.
"""

import uuid
from datetime import datetime, timezone

import fabric.functions as fn

udf = fn.UserDataFunctions()

APPROVED = "approved"
REJECTED = "rejected"

VERDICTS = ("wrong", "misleading", "right")

# Where an instruction takes effect. Agent instructions are applied after the
# query has run, so they change how an answer reads and nothing else.
TARGET_SEMANTIC_MODEL = "semantic_model"
TARGET_DATA_AGENT = "data_agent"


# --------------------------------------------------------------------------
# Shared
# --------------------------------------------------------------------------
#
# Caller-facing parameters are camelCase because Fabric refuses an underscore
# in a user data function parameter name. Column names keep their snake_case,
# because those are the schema's and nothing about the platform touches them.

def _caller(invocation):
    """The verified identity of whoever called this function.

    PreferredUsername is what a person recognises in an audit trail, but it is
    mutable, so the immutable object id is recorded next to it. Neither is
    supplied by the caller: both come from the token the platform validated.
    """
    user = (invocation.executing_user or {}) if invocation else {}
    name = (user.get("PreferredUsername") or "").strip()
    oid = (user.get("Oid") or "").strip()
    if not name and not oid:
        raise fn.UserThrownError(
            "Could not identify you, so nothing was recorded.",
            {"reason": "no executing_user on the invocation context"},
        )
    return name or oid, oid or name


def _cursor(sql_db):
    connection = sql_db.connect()
    return connection, connection.cursor()


def _question(value):
    value = (value or "").strip().upper()
    if not value:
        raise fn.UserThrownError(
            "Pick a question first.", {"reason": "question_id was empty"},
        )
    return value


def _now():
    return datetime.now(timezone.utc)


